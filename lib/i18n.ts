export type Lang = 'en' | 'te';
export type T = (key: string) => string;

export async function getLang(userLang?: Lang): Promise<Lang> {
  const c = (await cookies()).get('fm_lang')?.value;
  if (c === 'en' || c === 'te') return c;
  return userLang ?? 'en';
}

export function translator(lang: Lang): T {
  const dict = lang === 'te' ? te : en;
  return (key) => dict[key] ?? en[key] ?? key;
}
